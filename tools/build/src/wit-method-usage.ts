import * as fs from 'node:fs';
import * as path from 'node:path';
import * as ts from 'typescript';
import { BuildError } from './errors.ts';
import { createAnalysis } from './wit-method-usage/analysis.ts';
import { trackConstructors } from './wit-method-usage/constructors.ts';
import { trackEventRegistration } from './wit-method-usage/events.ts';
import { createUnseenImportCheck } from './wit-method-usage/imports.ts';
import { trackMemberAccess } from './wit-method-usage/members.ts';
import { WitUsageReport } from './wit-method-usage/report.ts';

/** WIT operations and event variants referenced by the plugin implementation. */
export interface UsedWitMethods {
    /** Sorted event names when registrations are static; `undefined` retains every event variant. */
    eventTypes: string[] | undefined;
    /** Sorted Pumpkin API operation identifiers required by the plugin. */
    pumpkinMethods: string[];
    /** Sorted WASI operation identifiers required by the plugin. */
    wasiMethods: string[];
}

/** Files to analyze for WIT operation usage. */
export interface WitMethodUsageOptions {
    /** Plugin entry file. Its nearest `tsconfig.json` supplies the compiler options. */
    entry: string;
    /** Absolute paths of the files esbuild bundled, from the build's metafile inputs. */
    inputs: readonly string[];
    /** Directory of generated declaration files for the plugin's WIT imports. */
    typesDir?: string;
    /** WIT the declarations were generated from, used to map jco's camelCase names back to WIT names. */
    witDir?: string;
}

/**
 * Select WIT operations referenced by the files esbuild bundled into the plugin.
 *
 * Dynamic keys retain every possible member. An input that is not a file on disk, such as a module
 * generated by another esbuild plugin, cannot reveal its host calls, so the result is `undefined`
 * to request full native adapters. Dynamic event registrations set `eventTypes` to `undefined` so
 * callers retain every event converter.
 *
 * @throws {BuildError} If the entry's `tsconfig.json` cannot be read or parsed.
 */
export function findUsedWitMethods({
    entry,
    inputs,
    typesDir,
    witDir,
}: WitMethodUsageOptions): UsedWitMethods | undefined {
    if (!fs.existsSync(entry)) return undefined;
    // esbuild reports real paths, so resolve symlinks before comparing them with TypeScript's files.
    const absoluteEntry = fs.realpathSync(path.resolve(entry));
    const implementationFiles: string[] = [];
    for (const input of inputs) {
        if (!fs.existsSync(input)) return undefined;
        // Other inputs are data such as JSON, which cannot call host operations.
        if (/\.[cm]?[jt]sx?$/.test(input)) implementationFiles.push(fs.realpathSync(input));
    }
    if (implementationFiles.length === 0) return undefined;
    const config = readCompilerConfig(absoluteEntry);
    const additionalTypeFiles = typesDir
        ? ts.sys.readDirectory(fs.realpathSync(typesDir), ['.d.ts'], undefined, ['**/*.d.ts'])
        : [];
    const report = new WitUsageReport(witDir);
    const program = ts.createProgram(
        [...new Set([...implementationFiles, ...config.declarationFiles, ...additionalTypeFiles])],
        config.options,
    );
    const pluginSources: ts.SourceFile[] = [];
    for (const fileName of implementationFiles) {
        const source = program.getSourceFile(fileName);
        if (!source) return undefined;
        pluginSources.push(source);
    }

    const analysis = createAnalysis(program, pluginSources, report);
    const importsUnseenCode = createUnseenImportCheck(program);
    const visit = (node: ts.Node): void => {
        if (importsUnseenCode(node)) report.incomplete = true;
        trackEventRegistration(analysis, node);
        trackMemberAccess(analysis, node);
        trackConstructors(analysis, node);
        ts.forEachChild(node, visit);
    };
    for (const source of pluginSources) visit(source);
    return report.result();
}

/**
 * Reads the compiler options of the entry's nearest `tsconfig.json`, or defaults when there is none,
 * and the declaration files that configuration includes.
 */
function readCompilerConfig(absoluteEntry: string): { options: ts.CompilerOptions; declarationFiles: string[] } {
    const configPath = ts.findConfigFile(path.dirname(absoluteEntry), ts.sys.fileExists, 'tsconfig.json');
    let parsed: ts.ParsedCommandLine;
    if (configPath) {
        const config = ts.readConfigFile(configPath, ts.sys.readFile);
        if (config.error) throw tsconfigError(configPath, [config.error]);
        parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, path.dirname(configPath));
    } else {
        parsed = ts.parseJsonConfigFileContent({}, ts.sys, path.dirname(absoluteEntry));
    }
    if (parsed.errors.length) throw tsconfigError(configPath ?? absoluteEntry, parsed.errors);
    return {
        options: {
            ...(configPath
                ? {}
                : {
                      target: ts.ScriptTarget.ES2022,
                      module: ts.ModuleKind.ESNext,
                      moduleResolution: ts.ModuleResolutionKind.Bundler,
                      strict: true,
                  }),
            ...parsed.options,
            allowJs: true,
            maxNodeModuleJsDepth: 100,
        },
        declarationFiles: parsed.fileNames.filter((fileName) => /\.d\.[cm]?ts$/.test(fileName)),
    };
}

function tsconfigError(configPath: string, diagnostics: readonly ts.Diagnostic[]): BuildError {
    const messages = diagnostics.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'));
    return new BuildError(`invalid TypeScript configuration ${configPath}:\n${messages.join('\n')}`);
}
