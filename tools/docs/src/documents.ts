import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { isAbsolute, relative, resolve, sep } from 'node:path';
import { applyBlocks, type BlockOptions } from './blocks.ts';

const DOCUMENT_NOTE = '<!-- Generated by pumpkin-plugins-docs. Edit source metadata, then run `pnpm readme`. -->';

/** Result of generation; check mode returns stale without writing. */
export type Status = 'updated' | 'unchanged' | 'stale';

/** One existing Markdown file and its generated blocks. Paths are relative to the supplied root. */
export interface BlockDocumentSpec extends BlockOptions {
    blocks: Record<string, string>;
    file: string;
    /** Omit to use the generic generation note; use an empty string to omit the note. */
    note?: string;
}

/** A whole-document transformation, used when generated values live outside marked blocks. */
export interface TransformDocumentSpec {
    file: string;
    transform: (source: string) => string;
}

/** A document update whose target must resolve inside the supplied root. */
export type DocumentSpec = BlockDocumentSpec | TransformDocumentSpec;

/** A validated document update, prepared before any generation writes. */
export interface DocumentUpdate {
    existing: string;
    file: string;
    next: string;
}

/** Resolve a document target and reject paths outside the supplied root. */
function resolveDocumentPath(root: string, file: string): string {
    const rootPath = resolve(root);
    const canonicalRootPath = realpathSync(rootPath);
    const requestedPath = resolve(rootPath, file);
    assertWithinRoot(rootPath, requestedPath);
    if (!existsSync(requestedPath)) {
        throw new Error(`${requestedPath} not found: create the document with generated block markers`);
    }

    const documentPath = realpathSync(requestedPath);
    assertWithinRoot(canonicalRootPath, documentPath);
    return documentPath;
}

/** Reject a target whose resolved path is not the root or one of its descendants. */
function assertWithinRoot(rootPath: string, documentPath: string): void {
    const relativePath = relative(rootPath, documentPath);
    if (relativePath === '..' || relativePath.startsWith(`..${sep}`) || isAbsolute(relativePath)) {
        throw new Error(`Documentation target ${documentPath} is outside root ${rootPath}`);
    }
}

/** Read and validate one document inside the supplied root; custom documents require all blocks unless opted out. */
export function prepareDocument(document: DocumentSpec, root: string): DocumentUpdate {
    const file = resolveDocumentPath(root, document.file);
    const existing = readFileSync(file, 'utf8');
    const next =
        'transform' in document
            ? document.transform(existing)
            : applyBlocks(existing, document.blocks, file, document.note ?? DOCUMENT_NOTE, {
                  required: document.required ?? true,
                  markers: document.markers,
              });
    return { file, existing, next };
}

/** Apply validated document updates or report drift without writing. */
export function writeDocuments(updates: readonly DocumentUpdate[], check = false): Status {
    let status: Status = 'unchanged';
    for (const update of updates) {
        if (update.existing === update.next) continue;
        if (check) status = 'stale';
        else {
            writeFileSync(update.file, update.next);
            status = 'updated';
        }
    }
    return status;
}

/** Validate every target before updating blocks; duplicate targets and malformed markers fail without writes. */
export function generateDocuments(documents: readonly DocumentSpec[], root: string, check = false): Status {
    const seen = new Set<string>();
    const updates = documents.map((document) => {
        const update = prepareDocument(document, root);
        if (seen.has(update.file)) throw new Error(`Duplicate documentation target: ${update.file}`);
        seen.add(update.file);
        return update;
    });
    return writeDocuments(updates, check);
}
