const readJson = (file: string) => JSON.parse(fs.readFileSync(file, 'utf8'));

function infoPath(pluginDir: string): string {
    const pkg = readJson(path.join(pluginDir, 'package.json'));
    return path.resolve(pluginDir, pkg.pumpkinPlugin?.info ?? 'src/info.ts');
}

/**
 * Loads the `info` export of a plugin's info module. Node strips the TypeScript types.
 * @param pluginDir - The plugin's folder.
 * @returns What the plugin says about itself.
 * @throws When the module is missing or doesn't export a usable `info`.
 */
export async function loadInfo(pluginDir: string): Promise<PluginInfo> {
    const file = infoPath(pluginDir);
    if (!fs.existsSync(file)) {
        throw new Error(`${file} not found: a plugin needs a src/info.ts that exports \`info\``);
    }
    const mod = await import(pathToFileURL(file).href);
    const info = mod.info ?? mod.default;
    if (typeof info?.name !== 'string' || typeof info?.description !== 'string') {
        throw new Error(`${file} must export an \`info\` object with a name and a description`);
    }
    return info;
}

/** The reason given in the nearest `release-please-paused.json` for holding back a component's releases. */
function pausedReason(directory: string): string | undefined {
    const component = path.resolve(directory);
    for (let root = component; ; root = path.dirname(root)) {
        const file = path.join(root, 'release-please-paused.json');
        if (fs.existsSync(file)) {
            const reason = readJson(file)[path.relative(root, component).split(path.sep).join('/') || '.'];
            return typeof reason === 'string' ? reason : undefined;
        }
        if (path.dirname(root) === root) return undefined;
    }
}

function routeUrl(siteUrl: URL, route: string): string {
    return new URL(encodeURI(route), siteUrl).href;
}

interface ComponentReference {
    apiRoute: string;
    file: string;
    guideLabel: string;
    guideRoute?: string;
}

async function packageReferences(
    root: string,
    group: 'packages' | 'tools' | 'extensions',
): Promise<ComponentReference[]> {
    const references: ComponentReference[] = [];
    for (const component of discoverComponents(root, group)) {
        const directory = component.directory;
        const readme = path.join(directory, 'README.md');
        if (!fs.existsSync(path.join(directory, 'src')) || !fs.existsSync(readme)) continue;
        const manifestFile = component.metadataFile;
        const manifest = readJson(manifestFile);
        if (group === 'packages' && !manifest.pumpkinPlugin) continue;
        if (group === 'packages') await loadInfo(directory);
        if (typeof manifest.name !== 'string' || !manifest.name) continue;

        const docsIndex = path.join(directory, 'docs', 'index.md');
        references.push({
            file: readme,
            apiRoute: componentApiRoute(group, component.slug, manifest.name),
            ...(fs.existsSync(docsIndex) ? { guideRoute: `${group}/${component.slug}/docs/` } : {}),
            guideLabel:
                group === 'packages' ? 'plugin guide' : group === 'extensions' ? 'extension guide' : 'tool guide',
        });
    }
    return references;
}

function actionReferences(root: string): ComponentReference[] {
    return actionRows(root).flatMap(({ dir }) => {
        const slug = path.basename(dir);
        const directory = path.join(root, dir);
        const file = path.join(directory, 'README.md');
        if (!fs.existsSync(file) || !fs.existsSync(path.join(directory, 'src'))) return [];
        return [
            {
                file,
                apiRoute: componentApiRoute('actions', slug),
                ...(fs.existsSync(path.join(directory, 'docs', 'index.md'))
                    ? { guideRoute: `actions/${slug}/docs/` }
                    : {}),
                guideLabel: 'action guide',
            },
        ];
    });
}

async function prepareComponentReferenceUpdates(root: string, siteUrl: URL): Promise<DocumentUpdate[]> {
    const references = [
        ...(await packageReferences(root, 'packages')),
        ...(await packageReferences(root, 'tools')),
        ...(await packageReferences(root, 'extensions')),
        ...actionReferences(root),
    ];
    const updates: DocumentUpdate[] = [];
    for (const reference of references) {
        const apiUrl = routeUrl(siteUrl, reference.apiRoute);
        const apiLink = `[API reference](${apiUrl})`;
        const body = reference.guideRoute
            ? `See the [${reference.guideLabel}](${routeUrl(siteUrl, reference.guideRoute)}) and ${apiLink} on the documentation site.`
            : `See the ${apiLink} on the documentation site.`;
        updates.push(
            prepareDocument({ file: reference.file, blocks: { reference: body }, note: REFERENCE_NOTE }, root),
        );
    }
    return updates;
}

/**
 * Refreshes the generated blocks of a plugin's README. Everything outside the blocks is kept.
 * @param pluginDir - The plugin's folder.
 * @param check - Only report whether the README is out of date, without writing.
 * @returns What happened to the README.
 * @throws When the README doesn't exist. `pnpm gen` creates one for new plugins.
 */
export async function generatePluginReadme(pluginDir: string, check = false): Promise<Status> {
    const info = await loadInfo(pluginDir);
    const pkg = readJson(path.join(pluginDir, 'package.json'));
    const output = pkg.pumpkinPlugin?.output;
    const release =
        typeof output === 'string'
            ? { output, packageName: pkg.name, unreleasedReason: pausedReason(pluginDir) }
            : undefined;
    return generateDocuments(
        [{ file: 'README.md', blocks: renderBlocks(info, release), required: false, note: GENERATED_NOTE }],
        pluginDir,
        check,
    );
}

async function rows(root: string, group: 'packages' | 'tools' | 'extensions'): Promise<PackageRow[]> {
    const out: PackageRow[] = [];
    for (const component of discoverComponents(root, group)) {
        const dir = component.directory;
        const pkg = readJson(component.metadataFile);
        // Plugins are shown by their Pumpkin name and description when they define them.
        const info = group === 'packages' && fs.existsSync(infoPath(dir)) ? await loadInfo(dir) : undefined;
        const licenseFile = localLicenseFile(dir);
        out.push({
            dir: `${group}/${component.slug}`,
            name: info?.name ?? (group === 'extensions' ? pkg.displayName : pkg.name),
            description: info?.description ?? pkg.description ?? '',
            license: pkg.license ?? '',
            licenseFile: licenseFile ? path.relative(root, licenseFile).split(path.sep).join('/') : undefined,
            unreleased: group === 'packages' && pausedReason(dir) !== undefined,
        });
    }
    return out;
}

function actionRows(root: string): ActionRow[] {
    return discoverComponents(root, 'actions').map((component) => {
        const metadata = readActionMetadata(component.metadataFile);
        const required = (key: 'name' | 'description'): string => {
            const value = metadata[key];
            if (value === undefined) throw new Error(`${component.metadataFile} is missing its top-level ${key}`);
            return value;
        };
        return { dir: `actions/${component.slug}`, name: required('name'), description: required('description') };
    });
}

/**
 * Refreshes the actions, plugin and tool tables in the repo's root README.
 * @param root - The repository root.
 * @param check - Only report whether the README is out of date, without writing.
 * @returns What happened to the README.
 * @throws When the README or its `packages` block is missing.
 */
export async function generateRootReadme(root: string, check = false): Promise<Status> {
    const rootPackage = readJson(path.join(root, 'package.json'));
    const siteUrl = githubPagesUrl(rootPackage.repository);
    if (!siteUrl)
        throw new Error(`${path.join(root, 'package.json')} needs a GitHub repository URL for documentation links`);
    const block = renderPackagesBlock(
        await rows(root, 'packages'),
        await rows(root, 'tools'),
        actionRows(root),
        await rows(root, 'extensions'),
    );
    const update = prepareDocument(
        {
            file: 'README.md',
            blocks: {
                packages: block,
                'docs-site': `Browse the [public documentation site](${siteUrl.href}) for guides, component overviews, and generated API references.`,
            },
            note: ROOT_NOTE,
        },
        root,
    );
    return writeDocuments([update, ...(await prepareComponentReferenceUpdates(root, siteUrl))], check);
}

/** Escape Markdown link labels without changing the stored page title. */
function escapeMarkdownLabel(value: string): string {
    return value.replace(/[\\[\]]/g, '\\$&').replace(/\|/g, '\\|');
}

/** Render a page as a source-relative link with its metadata description. */
function renderDocsPage(relativePath: string, title: string, description: string): string {
    const summary = description.trim() ? ` — ${description.trim().replace(/\s+/g, ' ')}` : '';
    return `- [${escapeMarkdownLabel(title)}](${relativePath})${summary}`;
}

/** Render one folder and its children as nested Markdown list items. */
function renderDocsFolder(folder: DocumentationTreeFolder, depth: number): string[] {
    const indent = '  '.repeat(depth);
    const label = folder.link
        ? `[${escapeMarkdownLabel(folder.text)}](${folder.indexPath ?? path.posix.join(folder.relativePath, 'index.md')})`
        : `**${escapeMarkdownLabel(folder.text)}**`;
    const description = folder.description?.trim() ? ` — ${folder.description.trim().replace(/\s+/g, ' ')}` : '';
    const lines = [`${indent}- ${label}${description}`];
    for (const item of folder.items) {
        if (item.kind === 'folder') lines.push(...renderDocsFolder(item, depth + 1));
        else {
            const rendered = renderDocsPage(item.relativePath, item.text, item.description);
            lines.push(`${'  '.repeat(depth + 1)}- ${rendered.slice(2)}`);
        }
    }
    return lines;
}

/** Render the generated Guides and folder-based Docs catalog. */
function renderDocsIndex(root: string): string {
    const pages = discoverHandwrittenDocs(root);
    const guides = pages.filter(({ section }) => section === 'guides');
    const guideGroups = new Map<string, typeof guides>();
    for (const guide of guides) {
        const category = guide.category ?? 'Guides';
        const group = guideGroups.get(category) ?? [];
        group.push(guide);
        guideGroups.set(category, group);
    }
    const guideSections = [...guideGroups.entries()]
        .sort(([left], [right]) => left.localeCompare(right))
        .flatMap(([category, entries]) => [
            `### ${category}`,
            '',
            ...entries
                .sort((left, right) => left.title.localeCompare(right.title))
                .map(({ relativePath, title, description }) => renderDocsPage(relativePath, title, description)),
            '',
        ]);
    if (guideSections.length) guideSections.pop();
    const docsEntries = buildDocumentationTree(pages).flatMap((folder, index) => [
        ...(index ? [''] : []),
        ...renderDocsFolder(folder, 0),
    ]);
    return [
        '## Guides',
        '',
        ...(guideSections.length ? guideSections : ['No guides yet.']),
        '',
        '## Docs',
        '',
        ...(docsEntries.length ? docsEntries : ['No docs yet.']),
    ].join('\n');
}

/**
 * Refresh or check the generated guide and docs menus in `docs/README.md`.
 * @param root - The repository root.
 * @param check - Only report whether the catalog is out of date.
 * @returns What happened to the catalog.
 */
export function generateDocsIndex(root: string, check = false): Status {
    return generateDocuments(
        [{ file: 'docs/README.md', blocks: { 'site-index': renderDocsIndex(root) }, note: DOCS_INDEX_NOTE }],
        root,
        check,
    );
}

